# A performance, not the record. Parenthesised forms are the strong signals;
# a bare "live" is not, because plenty of songs are called Live Forever.
LIVE_MARKERS = (
    r"\(\s*live\b", r"\[\s*live\b", r"\blive\s*\)", r"[-–]\s*live\b",
    r"\blive (?:at|in|from|on|version|performance|video|session)\b",
    r"\bin concert\b", r"\bconcert\b", r"\bunplugged\b", r"\bacoustic session\b",
    r"\b(?:aol|abbey road|bbc|kexp|npr) sessions?\b", r"\btiny desk\b",
    r"\bboiler room\b", r"\b(?:dj|full) set\b", r"\bsetlist\b",
    r"\bfestival\b", r"\btour\b", r"\bencore\b", r"\bcrowd\b",
)

# A video, which routinely means an intro, an outro, or dialogue over the top.
# Weezer's Buddy Holly video runs 4:02 against a 2:40 record.
VIDEO_MARKERS = (
    r"\bofficial (?:music )?video\b", r"\bmusic video\b", r"\bofficial mv\b",
    r"\(\s*video\s*\)", r"\bvisuali[sz]er\b", r"\bshort film\b",
)

NON_MUSIC_MARKERS = (r"\bgameplay\b", r"\bbeamng(?:\.drive)?\b", r"\b(?:gaming|car) montage\b",
                     r"\b(?:reaction|tutorial|walkthrough)\b")

# Alternate editions require an explicit request when original preference is on.
VARIANT_WORDS = (
    "acoustic", "unplugged", "demo", "alternate version", "alternative version",
    "alt version", "alt. version", "reprise", "rework", "radio edit",
    "single version", "extended mix", "extended version", "mono mix",
    "re-recorded", "rerecorded", "taylor's version", "instrumental version",
    "orchestral version", "piano version", "stripped",
)

# Descriptions that give the game away even when the title is clean.
LIVE_IN_DESCRIPTION = (
    r"\blive (?:at|in|from|performance|recording)\b", r"\brecorded live\b",
    r"\bperformed live\b", r"\bin concert\b",
    r"\blive audio\b",
)
VIDEO_IN_DESCRIPTION = (
    r"\bofficial (?:music )?video\b", r"\bmusic video by\b",
)

# Auto-generated uploads of the actual release. The single most reliable
# marker of release audio; it does not establish whether lyrics are censored.
ART_TRACK = (r"provided to youtube by", r"auto-?generated by youtube")

# Re-encoded, pitched or "enhanced" uploads.
TAMPERED = (r"artificial intelligence", r"\bai (?:remaster|upscal)",
            r"\bspeed(?:ed)? up\b", r"\bpitched\b", r"\bbass boost")


def _matches(text: str, patterns: tuple[str, ...], wanted: str) -> str | None:
    """First pattern that hits the text but not the thing we asked for.

    The guard matters: searching for Oasis' Live Forever must not reject every
    result for containing the word live.
    """
    for pattern in patterns:
        if re.search(pattern, text) and not re.search(pattern, wanted):
            return pattern
    return None


def classify(entry: dict[str, Any], artist: str, title: str) -> dict[str, Any]:
    """What kind of upload is this? Used for both rejection and ranking."""
    name = (entry.get("title") or "").lower()
    channel = (entry.get("channel") or entry.get("uploader") or "").lower()
    description = (entry.get("description") or "").lower()[:600]
    # The guard string carries both shapes a result can take, because search
    # titles are written "Artist - Title". Without the dashed form, asking for
    # AC/DC's Live Wire matches the "- live" marker and every single candidate
    # is thrown away.
    wanted = f"{artist} - {title} | {artist} {title}".lower()
    haystack = f"{name} {description}"

    art_track = bool(_matches(haystack, ART_TRACK, "")
                     or channel.endswith(" - topic"))
    official_audio = bool(re.search(r"\bofficial audio\b", name))

    # The title outranks the description when they disagree. Label boilerplate
    # is frequently wrong: Sony's upload of Blue In Green is titled "(Official
    # Audio)" and described as "Official music video for...", and the title is
    # the one telling the truth.
    titled_video = bool(_matches(name, VIDEO_MARKERS, wanted))
    described_video = bool(_matches(description, VIDEO_IN_DESCRIPTION, wanted))
    clean, explicit = versions.metadata_edition(entry, artist, title)

    return {
        "live": not versions._tagged(title, r"live(?:\s+(?:at|in|from)[^\])]+)?") and bool(_matches(name, LIVE_MARKERS, wanted)
                     or _matches(description, LIVE_IN_DESCRIPTION, wanted)
                     or (entry.get("live_status") or "") in
                     ("is_live", "was_live", "post_live")),
        "video": titled_video or (described_video and not
                                  (official_audio or art_track)),
        "non_music": bool(_matches(name, NON_MUSIC_MARKERS, wanted)),
        "art_track": art_track,
        "clean": clean,
        "explicit": explicit,
        "tampered": bool(_matches(haystack, TAMPERED, wanted)),
        "lyrics": bool(re.search(r"\blyrics?\b", name)),
        # Plain words rather than patterns, so asking for "Creep - Acoustic"
        # guards correctly against a result titled "Creep (Acoustic)". A
        # bracketed pattern would miss the dashed request entirely.
        "variant": any(word in name and word not in wanted
                       for word in VARIANT_WORDS) or any(
                           word not in wanted and re.search(r"\b" + word + r"\s+(?:version|performance|session|recording|take)\b", description)
                           for word in ("acoustic", "stripped", "unplugged")),
        "official_audio": bool(re.search(r"\bofficial audio\b", name)),
        "name": name, "channel": channel,
    }


def _candidate_score(entry: dict[str, Any], artist: str, title: str,
                     expected_ms: int, allow_video: bool = False
                     ) -> float | None:
    """Rank one search result. None means disqualified."""
    name = (entry.get("title") or "").lower()
    channel = (entry.get("channel") or entry.get("uploader") or "").lower()
    duration = entry.get("duration") or 0

    wanted = f"{artist} - {title} | {artist} {title}".lower()
    rejects = [str(k).lower() for k in
               (config.station.get("selection.reject_keywords") or [])]
    for word in rejects:
        # Only reject if the junk word isn't part of what we actually asked for.
        if word in name and word not in wanted:
            return None

    kind = classify(entry, artist, title)
    wants_clean = versions.is_clean_label(title)
    avoid_clean = config.station.get("selection.avoid_clean_versions", True)
    if avoid_clean and kind["clean"] and not wants_clean:
        return None
    if wants_clean and kind["explicit"]:
        return None
    if kind["live"] or kind["tampered"] or kind["non_music"]:
        return None
    if kind["variant"] and config.station.get("selection.prefer_original_recording", True):
        return None
    if kind["video"] and not allow_video:
        return None

    if expected_ms and duration:
        tolerance = float(config.station.get("selection.duration_tolerance", 0.18) or 0.18)
        expected = expected_ms / 1000.0
        if abs(duration - expected) / expected > tolerance:
            return None
    if duration and (duration < 45 or duration > 900):
        return None

    score = 0.0
    if (avoid_clean and kind["explicit"]) or (wants_clean and kind["clean"]):
        score += 2.0
    # An auto-generated upload of the release itself beats everything. The
    # description marker is what actually catches these -- the "- Topic"
    # channel suffix is usually absent from search results.
    if kind["art_track"]:
        score += 6.0
    if kind["official_audio"]:
        score += 3.0
    if kind["video"]:
        score -= 4.0        # only reachable on the fallback pass
    if kind["lyrics"]:
        score -= 2.5        # often re-encoded, sometimes pitched
    if kind["variant"]:
        # A different take of the same song. Enough to lose to a plain
        # version, not enough to be unusable when it is all there is.
        score -= 7.0
    if db.norm(artist) and db.norm(artist) in db.norm(name + " " + channel):
        score += 2.0
    if db.norm(title) and db.norm(title) in db.norm(name):
        score += 2.0
    if entry.get("channel_is_verified"):
        score += 1.0
    if expected_ms and duration:
        drift = abs(duration - expected_ms / 1000.0)
        score += max(0.0, 2.0 - drift / 5.0)
    return score


def _same_recording(entry: dict[str, Any], artist: str, title: str) -> bool:
    name = entry.get('title') or ''
    name = re.sub(r'\s*[\[(](?:official(?: music)?(?: video| audio)?|audio|lyrics?|explicit|uncensored)[^\])]*[\])]',
                  '', name, flags=re.I).strip()
    parts = re.split(r'\s[-–—]\s', name, maxsplit=1)
    credit, song = parts if len(parts) == 2 else ('', name)
    primary = db.norm(db.primary_artist(artist))
    channel = db.norm(entry.get('channel') or entry.get('uploader') or '')
    channel = re.sub(r'\s*(?:official|vevo|topic)$', '', channel).strip()
    named_artist = not primary or primary == 'unknown' or (
        primary in db.norm(credit) if credit else channel in (primary, db.norm(artist)))
    return db.norm(song) == db.norm(title) and named_artist


def _source_info(video_id: str) -> dict[str, Any]:
    """Cache source labels separately from catalogue titles and user edits."""
    if not re.fullmatch(r"[A-Za-z0-9_-]{11}", video_id or ""):
        return {}
    path = config.CACHE_DIR / "source-info" / f"{video_id}.json"
    try:
        info = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(info, dict) and info.get("id") == video_id:
            return info
    except (OSError, ValueError):
        pass
    try:
        info = sourceio.describe(video_id)
        if isinstance(info, dict) and info.get("title"):
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(json.dumps(info), encoding="utf-8")
            return info
    except (sourceio.SourceError, OSError):
        pass
    return {}


def _edition_check_path(video_id: str, artist: str, title: str) -> Path:
    identity = json.dumps([video_id, db.norm(artist), db.norm(title)], ensure_ascii=False)
    name = hashlib.sha256(identity.encode("utf-8")).hexdigest()
    return config.CACHE_DIR / "source-info" / "edition-checks" / (name + ".json")


def _edition_checked(video_id: str, artist: str, title: str) -> bool:
    try:
        data = json.loads(_edition_check_path(video_id, artist, title).read_text(encoding="utf-8"))
        # Version 1 compared titles only, and a clean auto-generated upload is
        # titled exactly like the explicit one. Those get looked at again.
        if data.get("version") != 2:
            return False
        if not data.get("success", True):
            ttl = 3600
        elif data.get("ytmusic"):
            ttl = 30 * 86400
        else:
            ttl = 6 * 3600  # titles only; ask YouTube Music again later
        return time.time() - float(data["at"]) < ttl
    except (OSError, ValueError, TypeError, KeyError):
        return False


def _edition_flagged(video_id: str, artist: str, title: str) -> bool:
    try:
        data = json.loads(_edition_check_path(video_id, artist, title).read_text(encoding="utf-8"))
        return data.get("version") == 2 and bool(data.get("ytmusic"))
    except (OSError, ValueError, TypeError, KeyError):
        return False


def _record_edition_check(video_id: str, artist: str, title: str, *, success=True,
                          flagged=False, status: str | None = None) -> None:
    # Evidence of an edition search, not a claim that audio is proven explicit.
    # `flagged` says YouTube Music's explicit flag was part of the answer.
    try:
        path = _edition_check_path(video_id, artist, title)
        path.parent.mkdir(parents=True, exist_ok=True)
        record = {"version": 2, "at": time.time(), "success": success, "ytmusic": bool(flagged)}
        if status:
            record["status"] = status
        path.write_text(json.dumps(record), encoding="utf-8")
    except OSError:
        pass


def resolve(artist: str, title: str, expected_ms: int = 0, *, exclude=()) -> str | None:
    """Return the best matching source video id, or None."""
    count = int(config.station.get("downloader.search_results", 5) or 5)
    query = f"ytsearch{count}:{artist} - {title}"
    options = {
        "quiet": True, "no_warnings": True, "skip_download": True,
        "extract_flat": "in_playlist", "socket_timeout": 15, "retries": 1,
        "default_search": "ytsearch",
    }
    info = sourceio.search(query, options)

    candidates = [e for e in ((info or {}).get("entries") or [])
                  if e and re.fullmatch(r"[\w-]{11}", e.get("id") or "")]

    prefer_explicit = (config.station.get("selection.avoid_clean_versions", True)
                       and not versions.is_clean_label(title))
    # An unlabelled Topic upload can be the clean edition, titled exactly like
    # the explicit one. YouTube Music's explicit flag tells them apart: when it
    # has an explicit release of this song, that goes to the front. When it
    # only has clean ones, the song has no explicit version and nothing else
    # changes. Exact source URLs bypass resolution entirely.
    hint = ytmusic.explicit_choice(artist, title, expected_ms) if prefer_explicit else None
    flagged = [song["video_id"] for song in (hint or {}).get("explicit", [])]
    if flagged:
        known = {entry["id"] for entry in candidates}
        for song in hint["explicit"]:
            if song["video_id"] not in known:
                # Scored on its own details below, like any search result.
                candidates.append({"id": song["video_id"], "title": song["title"],
                                   "duration": song["duration"] or None})
                known.add(song["video_id"])
    # Without that answer, compare a targeted search before accepting an
    # unlabelled upload, instead of searching only after every result has
    # already been rejected.
    searched_explicit = False
    if prefer_explicit and not (hint and hint["matched"]):
        try:
            extra = sourceio.search(query + " explicit audio", options)
            searched_explicit = True
            known = {entry["id"] for entry in candidates}
            for entry in ((extra or {}).get("entries") or []):
                if (entry and re.fullmatch(r"[\w-]{11}", entry.get("id") or "")
                        and entry["id"] not in known and _same_recording(entry, artist, title)):
                    candidates.append(entry)
                    known.add(entry["id"])
        except Exception as error:
            _log("explicit-edition search failed", artist, title, error)
    for allow_video in (False, True):
        if allow_video and config.station.get("selection.avoid_music_videos", True):
            continue
        ranked = []
        require_identity = any(entry['id'] in exclude for entry in candidates)
        for entry in candidates:
            if entry['id'] in exclude:
                continue
            if (prefer_explicit and classify(entry, artist, title)["explicit"]
                    and not _same_recording(entry, artist, title)):
                continue
            if require_identity:
                # A fallback must still identify this recording; a merely
                # high-ranked search result is not enough after the first fails.
                # YouTube Music already matched its releases by song and artist.
                if ((entry['id'] not in flagged and not _same_recording(entry, artist, title)) or
                        classify(entry, artist, title)['variant']):
                    continue
            score = _candidate_score(entry, artist, title, expected_ms,
                                     allow_video=allow_video)
            if score is None:
                continue
            ranked.append((score, entry))

        for score, entry in sorted(ranked, key=lambda candidate: (
                candidate[1]["id"] in flagged,
                prefer_explicit and classify(candidate[1], artist, title)["explicit"], candidate[0]),
                reverse=True):
            details = _source_info(entry["id"])
            entry = {**entry, **{k: v for k, v in details.items() if v is not None}}
            score = _candidate_score(entry, artist, title, expected_ms, allow_video=allow_video)
            if score is None:
                continue
            kind = classify(entry, artist, title)
            tags = [k for k in ("art_track", "official_audio", "video", "lyrics", "explicit", "clean")
                    if kind[k]] + (["flagged explicit"] if entry["id"] in flagged else [])
            _log("resolved", artist, "-", title, "->", entry["id"],
                 f"(score {score:.1f}"
                 + (f", {'+'.join(tags)}" if tags else "") + ")")
            if allow_video:
                _log("  only a video was available for", title)
            if flagged and entry["id"] not in flagged:
                _log("  no explicit release was usable for", title)
            if prefer_explicit and (searched_explicit or hint is not None):
                _record_edition_check(
                    entry["id"], artist, title, flagged=hint is not None,
                    status="explicit" if entry["id"] in flagged else
                    "no-explicit-version" if hint and hint["matched"] and not flagged else None)
            return entry["id"]

    _log("no acceptable match for", artist, "-", title,
         f"({len(candidates)} candidates rejected by source/version checks)")
    return None


