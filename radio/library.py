def _cache_path(video_id: str) -> Path:
    fmt = str(config.station.get("cache.format", "opus") or "opus")
    digest = hashlib.sha1(video_id.encode()).hexdigest()[:16]
    return AUDIO_DIR / f"{digest}.{fmt}"


TONAL_FIELDS = ("bpm", "bpm_confidence", "key_tonic", "key_mode", "key_confidence",
                "camelot", "beat_offset", "beat_period", "beat_residual_ms", "downbeat_offset")


def _mark_used(key: str) -> None:
    """Note that this file was just prepared. Eviction orders by it.

    Recorded in the database rather than by touching the file: the file's
    mtime is part of the waveform, structure and stem cache identities, and
    bumping it would throw all three away.
    """
    db.write("UPDATE tracks SET cache_used_at=? WHERE key=?", (time.time(), key))


def ensure(track: dict[str, Any]) -> dict[str, Any] | None:
    """Make sure this track is on disk, analysed, and ready to schedule.

    Blocking and slow on a cache miss -- always call this from the prefetch
    worker, never from the playout path.
    """
    key = track["key"]

    # Collapse duplicate requests for the same track into one download.
    with _RESOLVE_LOCK:
        event = _INFLIGHT.get(key)
        if event is None:
            event = threading.Event()
            _INFLIGHT[key] = event
            owner = True
        else:
            owner = False
    if not owner:
        event.wait(timeout=180)
        row = db.one("SELECT * FROM tracks WHERE key=?", (key,))
        if not row or not row["file"]:
            return None
        ready = dict(row)
        ready["structure"] = structure.profile_for(ready)
        _mark_used(key)
        return ready

    try:
        ready = _ensure_locked(track)
        if ready and ready.get("file"):
            _mark_used(key)
            # This prefetch worker is the only place that decodes for cue
            # analysis; timeline construction reads the prepared cache only.
            ready["structure"] = structure.profile(ready["file"])
        return ready
    finally:
        with _RESOLVE_LOCK:
            _INFLIGHT.pop(key, None)
        event.set()


def upgrade(track: dict[str, Any], video_id: str, protect=None) -> bool:
    """Swap a cached track to another upload of the same record, in the background.

    The old audio keeps playing until the new file is rendered and checked;
    then one row update points the track at it. A track the feeder is
    preparing right now is left alone. `protect` returns the files still
    wanted on air; the old file is deleted only when it is not one of them
    (without it, eviction gets to it in its own time).
    """
    key = track["key"]
    with _RESOLVE_LOCK:
        if key in _INFLIGHT:
            return False
        event = threading.Event()
        _INFLIGHT[key] = event
    try:
        before = db.one("SELECT * FROM tracks WHERE key=?", (key,))
        if not before or not before["file"] or before["video_id"] == video_id:
            return False
        ready = _ensure_locked(dict(track), replacement=video_id)
        swapped = bool(ready and ready.get("file") and ready.get("video_id") != before["video_id"])
        old = Path(before["file"])
        if swapped and protect is not None and _same_file_key(ready["file"]) != _same_file_key(old):
            try:
                keep = {_same_file_key(p) for p in (protect() or ()) if p}
                if (_same_file_key(old) not in keep
                        and not db.one("SELECT key FROM tracks WHERE file=?", (str(old),))):
                    old.unlink(missing_ok=True)
            except OSError:
                pass  # a reader still has it open; eviction will get it
        if swapped:
            _log("swapped", track.get("artist"), "-", track.get("title"), before["video_id"], "->", ready["video_id"])
        return swapped
    finally:
        with _RESOLVE_LOCK:
            _INFLIGHT.pop(key, None)
        event.set()


def _ensure_locked(track: dict[str, Any], replacement: str | None = None) -> dict[str, Any] | None:
    """`replacement` swaps cached audio for that upload, keeping the old file on failure."""
    key = track["key"]
    AUDIO_DIR.mkdir(parents=True, exist_ok=True)

    existing = db.one("SELECT * FROM tracks WHERE key=?", (key,))
    if existing and db.field(existing, "source_url"):
        from . import youtube
        track = youtube.hydrate(dict(existing))
        existing = track
    use_existing = True
    replacement_id = None
    fallback_existing = False
    verified_upgrade = False
    if replacement:
        # Local files and exact links are never swapped for another upload.
        if not (existing and existing["file"] and Path(existing["file"]).is_file()
                and db.field(existing, "source") != "local" and not db.field(existing, "source_url")):
            return dict(existing) if existing else None
        replacement_id, fallback_existing, use_existing, verified_upgrade = replacement, True, False, True
    elif (existing and existing["file"] and existing["video_id"]
            and db.field(existing, "source") != "local" and not db.field(existing, "source_url")
            and (config.station.get("selection.avoid_clean_versions", True)
                 or config.station.get("selection.prefer_original_recording", True)
                 or config.station.get("selection.avoid_music_videos", True))):
        info = _source_info(existing["video_id"])
        if (config.station.get("selection.avoid_clean_versions", True)
                and not versions.is_clean_label(track["title"])
                and not any(versions.metadata_edition(info, track["artist"], track["title"]))
                and _candidate_score(info, track["artist"], track["title"], track.get("expected_ms") or 0,
                    allow_video=not config.station.get("selection.avoid_music_videos", True)) is not None
                and not _edition_checked(existing["video_id"], track["artist"], track["title"])):
            fallback_existing = Path(existing["file"]).is_file()
            _log("checking explicit edition for cached recording", track["artist"], track["title"])
            # YouTube Music's flag first: it answers "is this upload the clean
            # one" directly, and only a proven clean upload with an explicit
            # sibling is replaced. Without an answer, search as before.
            found = ytmusic.verdict(existing["video_id"], track["artist"], track["title"],
                                    db.field(existing, "duration") or 0)
            if found is not None and found["status"] != "unknown":
                replacement_id = found["upgrade"]
                verified_upgrade = bool(replacement_id)
                _record_edition_check(existing["video_id"], track["artist"], track["title"],
                                      flagged=True, status=found["status"])
            else:
                try:
                    replacement_id = resolve(track["artist"], track["title"], track.get("expected_ms") or 0)
                except (sourceio.SourceError, OSError):
                    # This is an ambiguous working source, not a proven clean one.
                    # A network outage must not discard it or retry every pick.
                    replacement_id = None
                _record_edition_check(existing["video_id"], track["artist"], track["title"],
                                      success=bool(replacement_id and _edition_checked(
                                          replacement_id, track["artist"], track["title"])),
                                      flagged=bool(replacement_id and _edition_flagged(
                                          replacement_id, track["artist"], track["title"])))
            use_existing = not replacement_id or replacement_id == existing["video_id"]
        if info and _candidate_score(info, track["artist"], track["title"],
                                     track.get("expected_ms") or 0,
                                     allow_video=not config.station.get("selection.avoid_music_videos", True)) is None:
            use_existing = False
            _log("replacing alternate cached recording for", track["artist"], track["title"])
    if existing and existing["file"] and use_existing:
        path = Path(existing["file"])
        if path.exists():
            # Upgrade genre/embedded lyric evidence on the one track being
            # prepared, without rescanning the user's library or redoing DSP.
            from . import importer
            existing = importer.refresh_tags(dict(existing), path)
            # A file cached before tempo and key analysis existed would
            # otherwise never get it, because this early return skips the
            # whole pipeline. Fill the gap in place.
            if not db.field(existing, "bpm"):
                tonal = analysis.profile(path)
                db.write(
                    "UPDATE tracks SET bpm=?, bpm_confidence=?, key_tonic=?, "
                    "key_mode=?, key_confidence=?, camelot=?, beat_offset=?, "
                    "beat_period=?, beat_residual_ms=?, downbeat_offset=? WHERE key=?",
                    (tonal["bpm"], tonal["bpm_confidence"], tonal["key_tonic"],
                     tonal["key_mode"], tonal["key_confidence"],
                     tonal["camelot"], tonal["beat_offset"],
                     tonal["beat_period"], tonal["beat_residual_ms"],
                     tonal["downbeat_offset"], key))
                _log("backfilled analysis for", track.get("title"),
                     f"{tonal['bpm']:.0f}bpm {tonal['camelot'] or '?'}")
                existing = db.one("SELECT * FROM tracks WHERE key=?", (key,))
            return dict(existing)

    if existing and db.field(existing, "source") == "local":
        return None

    # A saved ID without usable audio may predate the edition preference.
    # Re-resolve it under the current rules instead of downloading it blindly.
    saved_id = existing["video_id"] if existing else None
    if (not db.field(existing, "source_url")
            and (config.station.get("selection.avoid_clean_versions", True)
                 or config.station.get("selection.prefer_original_recording", True)
                 or config.station.get("selection.avoid_music_videos", True))):
        saved_id = None
    try:
        video_id, raw = fetch_recording(
            track['artist'], track['title'], track.get('expected_ms') or 0,
            video_id=replacement_id or saved_id, pinned=bool(db.field(existing, 'source_url')), use_cache=True)
    except sourceio.SourceError:
        if not fallback_existing:
            raise
        _record_edition_check(existing["video_id"], track["artist"], track["title"], success=False)
        return dict(existing)
    if fallback_existing and (not video_id or not raw):
        _record_edition_check(existing["video_id"], track["artist"], track["title"], success=False)
        return dict(existing)
    if not video_id:
        db.write("UPDATE tracks SET blocked=1 WHERE key=?", (key,))
        return None
    if not fallback_existing:
        # A replacement moves video_id and file together, in the last write,
        # so the row never names one upload while playing another.
        db.write("UPDATE tracks SET video_id=? WHERE key=?", (video_id, key))

    def keep_existing() -> dict[str, Any]:
        _record_edition_check(existing["video_id"], track["artist"], track["title"], success=False)
        return dict(existing)

    final = _cache_path(video_id)
    measured: dict[str, Any] | None = None
    gain: float | None = None
    try:
        if not final.exists():
            if not raw:
                return keep_existing() if fallback_existing else None

            # Measure the source, then apply one gain. Analysing the raw file
            # also gets us the shape for free -- a linear gain does not move it.
            measured = measure(raw)
            gain = gain_for(measured["integrated"], measured["true_peak"])
            if not _render(raw, final, gain):
                return keep_existing() if fallback_existing else None
            _log(f"normalised {measured['integrated']:.1f} LUFS "
                 f"-> {measured['integrated'] + gain:.1f} ({gain:+.1f} dB)")
    finally:
        # The download is only ever a means to the render. Gone on success,
        # failure and timeout alike, so a crash-free run leaves no staging.
        if raw and raw != final:
            try:
                raw.unlink(missing_ok=True)
            except OSError:
                pass

    # The same recording this row already describes: what was measured and
    # analysed last time still holds, and decoding it again buys nothing.
    known = dict(existing) if existing and existing["video_id"] == video_id else {}
    reuse_shape = measured is None and all(
        known.get(name) is not None for name in ("duration", "intro_sec", "outro_sec", "lufs"))
    reuse_tonal = bool(known.get("bpm"))

    if reuse_shape:
        duration = float(known["duration"])
        stats = {"intro_sec": known["intro_sec"], "outro_sec": known["outro_sec"]}
        levels = {name: known.get(name) for name in
                  ("lufs", "source_lufs", "applied_gain_db", "true_peak")}
    else:
        if measured is None:  # cache hit on the audio, but no stored shape
            measured = measure(final)
        duration = float(measured.get("duration") or 0) or _probe_duration(final)
        stats = shape(measured["samples"], duration)
        if gain is not None:
            # Fresh render: lufs is what now plays, the rest is provenance.
            levels = {"lufs": measured["integrated"] + gain,
                      "source_lufs": measured["integrated"],
                      "applied_gain_db": gain,
                      "true_peak": measured["true_peak"] + gain}
        else:
            # Measured off the cached render itself, so it already is the
            # playing level; where it came from is only known if we kept it.
            levels = {"lufs": measured["integrated"],
                      "source_lufs": known.get("source_lufs"),
                      "applied_gain_db": known.get("applied_gain_db"),
                      "true_peak": measured["true_peak"]}

    old_length = float(db.field(existing, "duration") or 0) if existing else 0.0
    if (fallback_existing and video_id != existing["video_id"] and old_length
            and abs(duration - old_length) > max(8.0, old_length * 0.05)):
        # Another edition of one record runs within seconds of it. Anything
        # further off is some other recording: keep the one that works.
        _log("replacement runs", f"{duration:.0f}s against {old_length:.0f}s; keeping cached",
             track["artist"], "-", track["title"])
        if not db.one("SELECT key FROM tracks WHERE file=?", (str(final),)):
            try:
                final.unlink(missing_ok=True)
            except OSError:
                pass
        return keep_existing()

    # Tempo and key, so the director can pick a transition that suits the two
    # records rather than always reaching for the same crossfade.
    if reuse_tonal:
        tonal = {name: known.get(name) for name in TONAL_FIELDS}
    else:
        tonal = analysis.profile(final)

    db.write(
        "UPDATE tracks SET blocked=0, video_id=?, file=?, duration=?, intro_sec=?, outro_sec=?, "
        "lufs=?, source_lufs=?, applied_gain_db=?, true_peak=?, "
        "bpm=?, bpm_confidence=?, key_tonic=?, key_mode=?, "
        "key_confidence=?, camelot=?, beat_offset=?, beat_period=?, "
        "beat_residual_ms=?, downbeat_offset=?, cache_used_at=? WHERE key=?",
        (video_id, str(final), duration, stats["intro_sec"], stats["outro_sec"],
         levels["lufs"], levels["source_lufs"], levels["applied_gain_db"], levels["true_peak"],
         tonal["bpm"], tonal["bpm_confidence"],
         tonal["key_tonic"], tonal["key_mode"], tonal["key_confidence"],
         tonal["camelot"], tonal["beat_offset"], tonal["beat_period"],
         tonal["beat_residual_ms"], tonal["downbeat_offset"], time.time(), key),
    )
    if verified_upgrade and video_id == replacement_id:
        # YouTube Music named this upload as the explicit release.
        _record_edition_check(video_id, track["artist"], track["title"], flagged=True, status="explicit")
    _log("ready", track["artist"], "-", track["title"],
         f"{duration:.0f}s intro={stats['intro_sec']:.1f}s "
         f"outro={stats['outro_sec']:.1f}s "
         f"{tonal['bpm']:.0f}bpm {tonal['camelot'] or '?'}")
    row = db.one("SELECT * FROM tracks WHERE key=?", (key,))
    return dict(row) if row else None


