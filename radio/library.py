def _ffmpeg(args: list[str], timeout: int = 300) -> subprocess.CompletedProcess:
    return subprocess.run(
        [config.FFMPEG, "-hide_banner", "-nostdin", "-y", *args],
        capture_output=True, text=True, timeout=timeout,
        creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
    )


def _download_raw(video_id: str, destination: Path) -> Path | None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    # Console pulls and radio can fetch the same song in separate processes.
    # Each owns its staging files, including any .part file left on failure.
    destination = destination.with_name(destination.name + "_" + uuid.uuid4().hex)
    options = {
        "quiet": True, "no_warnings": True,
        "format": "bestaudio/best",
        "outtmpl": str(destination.with_suffix(".%(ext)s")),
        "socket_timeout": 20, "retries": 2,
        "noplaylist": True,
        "overwrites": True,
    }
    try:
        sourceio.download(video_id, options)
    except Exception:
        for part in destination.parent.glob(destination.name + ".*"):
            part.unlink(missing_ok=True)
        raise
    matches = sorted(destination.parent.glob(destination.stem + ".*"))
    return matches[0] if matches else None


def _unavailable(error: Exception) -> bool:
    """Only source-specific failures warrant trying a different upload."""
    message = str(error).lower()
    return any(phrase in message for phrase in (
        'please sign in', 'sign in to confirm', 'video unavailable',
        'video is unavailable', 'private video', 'video has been removed',
        'not available in your country', 'copyright', 'http error 403',
        'requested format is not available'))


def fetch_recording(artist: str, title: str, expected_ms: int = 0, *,
                    video_id: str | None = None, pinned: bool = False,
                    use_cache: bool = False, on_attempt=None) -> tuple[str, Path | None]:
    """Try up to three matching uploads; explicit video links stay pinned.

    Returns the chosen ID and raw audio, or the finished cache file on a hit.
    Timeouts and disk/encoding failures do not trigger another download.
    """
    if pinned and not video_id:
        raise sourceio.SourceError('The requested video link has no usable video ID.')
    excluded = {row['video_id'] for row in db.query(
        'SELECT video_id FROM unavailable_sources WHERE retry_after>?', (time.time(),))}
    attempted = set()
    last_error = None
    for attempt in range(1 if pinned else 3):
        if not video_id or (not pinned and video_id in excluded):
            video_id = resolve(artist, title, expected_ms, exclude=excluded | attempted)
        if not video_id or video_id in attempted:
            break
        attempted.add(video_id)
        if on_attempt:
            on_attempt(video_id, attempt)
        cached = _cache_path(video_id)
        if use_cache and cached.is_file():
            return video_id, cached
        try:
            raw = _download_raw(video_id, AUDIO_DIR / f'.raw_{video_id}')
            if raw:
                db.write('DELETE FROM unavailable_sources WHERE video_id=?', (video_id,))
            return video_id, raw
        except sourceio.SourceError as error:
            if pinned or not _unavailable(error):
                raise
            last_error = error
            excluded.add(video_id)
            db.write('INSERT OR REPLACE INTO unavailable_sources(video_id,retry_after,reason) VALUES(?,?,?)',
                     (video_id, time.time() + 86400, str(error)[:400]))
            _log('source unavailable; trying another matching upload', video_id)
            video_id = None
    if last_error:
        raise sourceio.SourceError('Matching uploads were unavailable. Try another video link or retry later. '
                                   + str(last_error)[:220]) from last_error
    return '', None


def _render(source: Path, target: Path, gain_db: float,
            fmt: str | None = None) -> bool:
    """Apply a single linear gain and encode to the working format.

    Deliberately NOT ffmpeg's one-pass `loudnorm`, which is a dynamic
    processor: it flattens a mastered record to about 1 LU of range, which
    kills the contrast that makes ducking and crossfades audible. Measuring
    first and applying one gain keeps the record's own dynamics intact.
    """
    rate = int(config.station.get("audio.sample_rate", 48000) or 48000)
    fmt = fmt or str(config.station.get("cache.format", "opus") or "opus")

    if fmt == "opus":
        codec = ["-c:a", "libopus", "-b:a",
                 str(config.station.get("cache.opus_bitrate", "160k") or "160k")]
    elif fmt == "flac":
        codec = ["-c:a", "flac", "-compression_level", "5"]
    elif fmt in ("m4a", "aac"):
        codec = ["-c:a", "aac", "-b:a",
                 str(config.station.get("cache.aac_bitrate", "192k") or "192k")]
    else:
        codec = ["-c:a", "pcm_s16le"]

    # A gentle limiter only catches the rare inter-sample overshoot; with the
    # gain already ceiling-limited it should almost never engage.
    chain = f"volume={gain_db:.2f}dB,alimiter=limit=0.97:level=disabled"

    result = _ffmpeg([
        "-i", str(source), "-vn", "-map_metadata", "-1",
        "-af", chain, "-ar", str(rate), "-ac", "2",
        *codec, str(target),
    ])
    if result.returncode != 0:
        _log("render failed", result.stderr[-500:])
        return False
    return target.exists() and target.stat().st_size > 1024


_FRAME = re.compile(r"t:\s*([\d.]+).*?\sS:\s*(-?[\d.]+|-inf)")
_INTEGRATED = re.compile(r"^\s*I:\s*(-?[\d.]+|-inf)\s*LUFS", re.MULTILINE)
_TRUE_PEAK = re.compile(r"Peak:\s*(-?[\d.]+|-inf)\s*dBFS")


def measure(path: Path) -> dict[str, Any]:
    """One ebur128 pass: integrated loudness, true peak, loudness envelope.

    The envelope is what tells us where a record actually starts. Where
    short-term loudness first climbs to within a few LU of the track's median
    and stays there is, in practice, the end of the intro -- the window a DJ
    talks over.
    """
    result = _ffmpeg(["-i", str(path), "-af", "ebur128=framelog=info:peak=true",
                      "-f", "null", "-"], timeout=240)
    stderr = result.stderr or ""

    samples: list[tuple[float, float]] = []
    for line in stderr.splitlines():
        match = _FRAME.search(line)
        if not match:
            continue
        try:
            moment = float(match.group(1))
            short_term = float(match.group(2))
        except ValueError:
            continue  # -inf during leading silence
        if short_term > -70:
            samples.append((moment, short_term))

    def _last(pattern: re.Pattern[str], default: float) -> float:
        found = pattern.findall(stderr)
        try:
            return float(found[-1]) if found else default
        except ValueError:
            return default

    return {
        "integrated": _last(_INTEGRATED, -23.0),
        "true_peak": _last(_TRUE_PEAK, -1.0),
        "samples": samples,
    }


def shape(samples: list[tuple[float, float]], duration: float) -> dict[str, float]:
    """Turn a loudness envelope into intro and outro points."""
    fallback = float(config.station.get("talk_placement.assumed_intro", 12.0) or 12.0)
    if len(samples) < 8:
        return {"intro_sec": fallback, "outro_sec": max(0.0, duration - 8.0)}

    values = sorted(value for _, value in samples)
    median = values[len(values) // 2]

    intro = _sustained_crossing(samples, median - 3.0, hold=1.5)
    intro = min(max(intro if intro is not None else fallback, 0.0), 45.0)

    outro = _last_crossing(samples, median - 6.0)
    if outro is None:
        outro = max(0.0, duration - 8.0)

    return {"intro_sec": intro, "outro_sec": outro}


def gain_for(integrated: float, true_peak: float) -> float:
    """Gain in dB to hit the target loudness without clipping."""
    target = float(config.station.get("audio.target_lufs", -14.0) or -14.0)
    ceiling = float(config.station.get("audio.true_peak_ceiling", -1.5) or -1.5)
    wanted = target - integrated
    headroom = ceiling - true_peak
    # Never push a track into the ceiling just to hit the loudness target.
    return max(-24.0, min(wanted, headroom, 24.0))


def _sustained_crossing(samples: list[tuple[float, float]], threshold: float,
                        hold: float) -> float | None:
    """First moment loudness goes above `threshold` and stays for `hold` sec."""
    start: float | None = None
    for moment, value in samples:
        if value >= threshold:
            if start is None:
                start = moment
            elif moment - start >= hold:
                return start
        else:
            start = None
    return None


def _last_crossing(samples: list[tuple[float, float]], threshold: float) -> float | None:
    for moment, value in reversed(samples):
        if value >= threshold:
            return moment
    return None


def _probe_duration(path: Path) -> float:
    try:
        result = subprocess.run(
            ["ffprobe", "-v", "error", "-show_entries", "format=duration",
             "-of", "json", str(path)],
            capture_output=True, text=True, timeout=30,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
        return float(json.loads(result.stdout)["format"]["duration"])
    except Exception:  # noqa: BLE001
        return 0.0


