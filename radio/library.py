def _cache_path(video_id: str) -> Path:
    fmt = str(config.station.get("cache.format", "opus") or "opus")
    digest = hashlib.sha1(video_id.encode()).hexdigest()[:16]
    return AUDIO_DIR / f"{digest}.{fmt}"


def ensure(track: dict[str, Any]) -> dict[str, Any] | None:
    """Make sure this track is on disk, analysed, and ready to schedule.

    Blocking and slow on a cache miss -- always call this from the prefetch
    worker, never from the playout path.
    """
    key = track["key"]

    # Collapse duplicate requests for the same track into one download.
    with _RESOLVE_LOCK:
        event = _INFLIGHT.get(key)
        if event is None:
            event = threading.Event()
            _INFLIGHT[key] = event
            owner = True
        else:
            owner = False
    if not owner:
        event.wait(timeout=180)
        row = db.one("SELECT * FROM tracks WHERE key=?", (key,))
        if not row or not row["file"]:
            return None
        ready = dict(row)
        ready["structure"] = structure.profile_for(ready)
        return ready

    try:
        ready = _ensure_locked(track)
        if ready and ready.get("file"):
            # This prefetch worker is the only place that decodes for cue
            # analysis; timeline construction reads the prepared cache only.
            ready["structure"] = structure.profile(ready["file"])
        return ready
    finally:
        with _RESOLVE_LOCK:
            _INFLIGHT.pop(key, None)
        event.set()


def _ensure_locked(track: dict[str, Any]) -> dict[str, Any] | None:
    key = track["key"]
    AUDIO_DIR.mkdir(parents=True, exist_ok=True)

    existing = db.one("SELECT * FROM tracks WHERE key=?", (key,))
    if existing and db.field(existing, "source_url"):
        from . import youtube
        track = youtube.hydrate(dict(existing))
        existing = track
    use_existing = True
    if (existing and existing["file"] and existing["video_id"]
            and db.field(existing, "source") != "local" and not db.field(existing, "source_url")
            and config.station.get("selection.prefer_original_recording", True)):
        info = _source_info(existing["video_id"])
        if info and _candidate_score(info, track["artist"], track["title"],
                                     track.get("expected_ms") or 0, allow_video=True) is None:
            use_existing = False
            _log("replacing alternate cached recording for", track["artist"], track["title"])
    if existing and existing["file"] and use_existing:
        path = Path(existing["file"])
        if path.exists():
            # Upgrade genre/embedded lyric evidence on the one track being
            # prepared, without rescanning the user's library or redoing DSP.
            from . import importer
            existing = importer.refresh_tags(dict(existing), path)
            # A file cached before tempo and key analysis existed would
            # otherwise never get it, because this early return skips the
            # whole pipeline. Fill the gap in place.
            if not db.field(existing, "bpm"):
                tonal = analysis.profile(path)
                db.write(
                    "UPDATE tracks SET bpm=?, bpm_confidence=?, key_tonic=?, "
                    "key_mode=?, key_confidence=?, camelot=?, beat_offset=?, "
                    "beat_period=?, beat_residual_ms=?, downbeat_offset=? WHERE key=?",
                    (tonal["bpm"], tonal["bpm_confidence"], tonal["key_tonic"],
                     tonal["key_mode"], tonal["key_confidence"],
                     tonal["camelot"], tonal["beat_offset"],
                     tonal["beat_period"], tonal["beat_residual_ms"],
                     tonal["downbeat_offset"], key))
                _log("backfilled analysis for", track.get("title"),
                     f"{tonal['bpm']:.0f}bpm {tonal['camelot'] or '?'}")
                existing = db.one("SELECT * FROM tracks WHERE key=?", (key,))
            return dict(existing)

    if existing and db.field(existing, "source") == "local":
        return None

    # A saved ID without usable audio may predate the edition preference.
    # Re-resolve it under the current rules instead of downloading it blindly.
    saved_id = existing["video_id"] if existing else None
    if (not db.field(existing, "source_url")
            and (config.station.get("selection.avoid_clean_versions", True)
                 or config.station.get("selection.prefer_original_recording", True))):
        saved_id = None
    video_id, raw = fetch_recording(
        track['artist'], track['title'], track.get('expected_ms') or 0,
        video_id=saved_id, pinned=bool(db.field(existing, 'source_url')), use_cache=True)
    if not video_id:
        db.write("UPDATE tracks SET blocked=1 WHERE key=?", (key,))
        return None
    db.write("UPDATE tracks SET video_id=? WHERE key=?", (video_id, key))

    final = _cache_path(video_id)
    measured: dict[str, Any] | None = None
    if raw and raw != final and final.exists():
        raw.unlink(missing_ok=True)

    if not final.exists():
        if not raw:
            return None

        # Measure the source, then apply one gain. Analysing the raw file also
        # gets us the shape for free -- a linear gain does not move it.
        measured = measure(raw)
        gain = gain_for(measured["integrated"], measured["true_peak"])
        ok = _render(raw, final, gain)
        try:
            raw.unlink()
        except OSError:
            pass
        if not ok:
            return None
        _log(f"normalised {measured['integrated']:.1f} LUFS "
             f"-> {measured['integrated'] + gain:.1f} ({gain:+.1f} dB)")

    if measured is None:  # cache hit on the audio, but no stored shape
        measured = measure(final)

    duration = _probe_duration(final)
    stats = shape(measured["samples"], duration)

    # Tempo and key, so the director can pick a transition that suits the two
    # records rather than always reaching for the same crossfade.
    tonal = analysis.profile(final)

    db.write(
        "UPDATE tracks SET blocked=0, file=?, duration=?, intro_sec=?, outro_sec=?, "
        "lufs=?, bpm=?, bpm_confidence=?, key_tonic=?, key_mode=?, "
        "key_confidence=?, camelot=?, beat_offset=?, beat_period=?, "
        "beat_residual_ms=?, downbeat_offset=? WHERE key=?",
        (str(final), duration, stats["intro_sec"], stats["outro_sec"],
         measured["integrated"], tonal["bpm"], tonal["bpm_confidence"],
         tonal["key_tonic"], tonal["key_mode"], tonal["key_confidence"],
         tonal["camelot"], tonal["beat_offset"], tonal["beat_period"],
         tonal["beat_residual_ms"], tonal["downbeat_offset"], key),
    )
    _log("ready", track["artist"], "-", track["title"],
         f"{duration:.0f}s intro={stats['intro_sec']:.1f}s "
         f"outro={stats['outro_sec']:.1f}s "
         f"{tonal['bpm']:.0f}bpm {tonal['camelot'] or '?'}")
    row = db.one("SELECT * FROM tracks WHERE key=?", (key,))
    return dict(row) if row else None


