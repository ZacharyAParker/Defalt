"""Getting audio onto disk, at a consistent level, with its shape measured.

Pipeline per track:
    resolve  -> pick the best source match. Refuses live takes, music videos,
                karaoke, covers and pitched re-uploads; prefers the
                auto-generated upload of the actual release
    fetch    -> download bestaudio
    render   -> loudness-normalise to the configured LUFS, encode to opus
    analyse  -> parse the ebur128 loudness envelope to find where the track
                actually starts and where it winds down

That last step is what lets the hosts talk up the post: we know when the
music arrives, so we know when to stop speaking.

See NOTICE.md. Audio here is transient, local, personal, and never served
outside this machine.
"""
